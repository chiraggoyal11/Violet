/** Digits only, max 6. */
export function sanitizePincode(value) {
  return String(value || '')
    .replace(/\D/g, '')
    .slice(0, 6);
}

export function isValidPincode(value) {
  return /^\d{6}$/.test(String(value || '').trim());
}
